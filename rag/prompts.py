def reply_language(lang: str, *, chat: bool = False) -> str:
    """界面是英文时，要求回答用英文。中文界面返回空字符串。"""
    if (lang or "").strip().lower() != "en":
        return ""
    if chat:
        return (
            "The interface language is English. Reply in English, in one or two natural sentences. "
            "Do not answer in Chinese."
        )
    return (
        "The interface language is English. Write the whole answer in English. "
        "Keep each quoted classical sentence in Chinese characters, and give its English translation immediately after it. "
        "In Textual Study, the only headings allowed are Original and Translation. "
        "Explanations, steps, and closing lines must be English, not Chinese. "
        "Book titles may stay in Chinese, such as 《论语》."
    )


def system_prompt(mode: str, lang: str = "zh") -> str:
    extra = reply_language(lang)
    if not extra:
        return SYSTEM_PROMPTS[mode]
    return SYSTEM_PROMPTS[mode] + "\n\n" + extra


def chat_prompt(lang: str = "zh") -> str:
    extra = reply_language(lang, chat=True)
    if not extra:
        return CHAT_PROMPT
    return CHAT_PROMPT + "\n\n" + extra
